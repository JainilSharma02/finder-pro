/**
 * Rapid Search in Local Database + Live India Post API fallback
 */
export const searchLocationsAndPincodes = async (query) => {
  const q = (query || '').trim().toLowerCase();
  if (!q) return [];

  const results = [];
  const isDigitsOnly = /^\d+$/.test(q);

  // 1. PINCODE LOOKUP (by digits)
  if (isDigitsOnly) {
    const localMatches = POPULAR_PINCODES.filter(item => 
      item.pincode.startsWith(q)
    ).slice(0, 12);

    localMatches.forEach(item => {
      results.push({
        type: 'pincode',
        display: `${item.pincode} - ${item.area}, ${item.city}`,
        value: `${item.city} ${item.pincode}`,
        pincode: item.pincode,
        area: item.area,
        city: item.city,
        state: item.state
      });
    });

    // If 6 exact digits, fetch real-time from India Post API if fewer local matches
    if (q.length === 6 && results.length < 3) {
      try {
        const resp = await fetch(`https://api.postalpincode.in/pincode/${q}`);
        if (resp.ok) {
          const data = await resp.json();
          if (data && data[0] && data[0].Status === 'Success' && Array.isArray(data[0].PostOffice)) {
            const offices = data[0].PostOffice.slice(0, 8);
            offices.forEach(po => {
              const poDisplay = `${q} - ${po.Name}, ${po.District || po.Division}`;
              if (!results.some(r => r.display === poDisplay)) {
                results.push({
                  type: 'pincode',
                  display: poDisplay,
                  value: `${po.District || po.Name} ${q}`,
                  pincode: q,
                  area: po.Name,
                  city: po.District || po.Division,
                  state: po.State
                });
              }
            });
          }
        }
      } catch (_) {}
    }

    return results;
  }

  // 2. TEXT SEARCH (By City, Taluka, Town or Area Name)
  // Check in Cities & Districts
  const cityMatches = INDIAN_CITIES_AND_DISTRICTS.filter(item =>
    item.name.toLowerCase().includes(q) || item.state.toLowerCase().includes(q)
  ).slice(0, 8);

  cityMatches.forEach(item => {
    results.push({
      type: 'city',
      display: `${item.name}, ${item.state}`,
      value: item.name.split('(')[0].trim(),
      city: item.name,
      state: item.state,
      tag: item.type
    });
  });

  // Check in Pincode Area / Locality names
  const areaMatches = POPULAR_PINCODES.filter(item =>
    item.area.toLowerCase().includes(q) || item.city.toLowerCase().includes(q)
  ).slice(0, 8);

  areaMatches.forEach(item => {
    const val = `${item.city} ${item.pincode}`;
    if (!results.some(r => r.value === val)) {
      results.push({
        type: 'pincode',
        display: `${item.pincode} - ${item.area}, ${item.city}`,
        value: val,
        pincode: item.pincode,
        area: item.area,
        city: item.city,
        state: item.state
      });
    }
  });

  return results.slice(0, 12);
};
